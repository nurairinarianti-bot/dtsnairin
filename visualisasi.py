import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# Memuat ulang data untuk memastikan df1 terdefinisi
url = "https://raw.githubusercontent.com/Alam-A99/DATAAKSI/refs/heads/main/dataset_fiskal_97_hipoFull.csv"
df1 = pd.read_csv(url)

# Boxplot (Sebaran Kemiskinan & Outlier)
plt.figure(figsize=(6, 5))
sns.boxplot(data=df1, y='KEMISKINAN', color='salmon', width=0.4)

plt.title('Sebaran Tingkat Kemiskinan', fontsize=12, fontweight='bold')
plt.ylabel('Persentase Kemiskinan (%)')
plt.tight_layout()
plt.show()

# Boxplot (Sebaran IPM & Outlier)
# Melihat median, kuartil, dan daerah mana yang menjadi outlier (pencilan) dalam IPM.
plt.figure(figsize=(6, 5))
sns.boxplot(data=df1, y='IPM', color='skyblue', width=0.4)

plt.title('Sebaran Indeks Pembangunan Manusia (IPM)', fontsize=12, fontweight='bold')
plt.ylabel('Nilai IPM (0-100)')
plt.tight_layout()
plt.show()